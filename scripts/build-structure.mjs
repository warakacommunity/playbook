// build-structure.mjs — the SINGLE source of truth for the playbook structure.
//
// Resolves sidebars.js (the site's real chapter organisation) into a flat
// static/structure.json that the in-browser Contribute editor reads, so the
// editor tree is identical to the site sidebar. Each entry carries its source
// file path and `ready` flag; the editor makes not-ready (under-development)
// chapters read-only.
//
// Runs at prebuild (see package.json). Output is served at
// <baseUrl>structure.json on the deployed site.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DOCS = path.join(ROOT, 'docs');

// Docusaurus default number-prefix parser: strip a leading "<digits><sep>"
// from each path segment (e.g. "1_introduction" -> "introduction").
const stripNum = (seg) => seg.replace(/^\d+[-_.\s]+/, '');
const toDocId = (rel) => rel.replace(/\.mdx?$/, '').split('/').map(stripNum).join('/');

// Minimal frontmatter read (between the first two --- lines) + first # heading.
function meta(file) {
  const txt = fs.readFileSync(file, 'utf8');
  const fm = {};
  const m = txt.match(/^---\n([\s\S]*?)\n---/);
  if (m) {
    for (const line of m[1].split('\n')) {
      const kv = line.match(/^(\w+):\s*(.*)$/);
      if (kv) fm[kv[1]] = kv[2].replace(/^["']|["']$/g, '').trim();
    }
  }
  const heading = txt.match(/^#\s+(.+)$/m);
  return {
    ready: fm.ready === 'true' || fm.ready === true,
    title: fm.title || fm.sidebar_label || (heading && heading[1]) || null,
  };
}

// Build id -> { path, ready, title } for every doc file.
function buildIndex() {
  const index = {};
  (function walk(dir) {
    for (const name of fs.readdirSync(dir)) {
      const full = path.join(dir, name);
      if (fs.statSync(full).isDirectory()) walk(full);
      else if (/\.mdx?$/.test(name)) {
        const rel = path.relative(DOCS, full).split(path.sep).join('/');
        const { ready, title } = meta(full);
        index[toDocId(rel)] = { path: 'docs/' + rel, ready, title };
      }
    }
  })(DOCS);
  return index;
}

// Ordered doc ids under a folder (mirrors Docusaurus autogenerated ordering:
// index first, then by numeric prefix, then alphabetical).
function autogen(dirName) {
  const abs = path.join(DOCS, dirName);
  const ids = [];
  const order = (a, b) => {
    if (/^index\./.test(a)) return -1;
    if (/^index\./.test(b)) return 1;
    const na = (a.match(/^(\d+)/) || [])[1];
    const nb = (b.match(/^(\d+)/) || [])[1];
    if (na && nb) return +na - +nb;
    return a.localeCompare(b);
  };
  (function walk(dir) {
    for (const name of fs.readdirSync(dir).sort(order)) {
      const full = path.join(dir, name);
      if (fs.statSync(full).isDirectory()) walk(full);
      else if (/\.mdx?$/.test(name)) {
        ids.push(toDocId(path.relative(DOCS, full).split(path.sep).join('/')));
      }
    }
  })(abs);
  return ids;
}

let missing = 0;
const docNode = (id, index, labelOverride) => {
  const m = index[id];
  if (!m) { console.warn('[structure] no file for sidebar id:', id); missing++; return null; }
  return { type: 'doc', id, label: labelOverride || m.title || id.split('/').pop(), path: m.path, ready: m.ready };
};

function resolve(item, index) {
  if (typeof item === 'string') return docNode(item, index);
  if (!item || typeof item !== 'object') return null;

  if (item.type === 'autogenerated') {
    return { type: 'group', label: stripNum(item.dirName), items: autogen(item.dirName).map((id) => docNode(id, index)).filter(Boolean) };
  }
  if (item.type === 'category') {
    const items = [];
    if (item.link?.type === 'doc' && item.link.id) {
      const n = docNode(item.link.id, index, 'Overview');
      if (n) items.push(n);
    }
    for (const sub of item.items || []) {
      if (sub?.type === 'autogenerated') {
        for (const id of autogen(sub.dirName)) { const n = docNode(id, index); if (n) items.push(n); }
      } else {
        const n = resolve(sub, index);
        if (n) items.push(n);
      }
    }
    return { type: 'group', label: item.label, items };
  }
  return null;
}

const sidebars = (await import(pathToFileURL(path.join(ROOT, 'sidebars.js')).href)).default;
const index = buildIndex();
const tree = (sidebars.tutorialSidebar || []).map((i) => resolve(i, index)).filter(Boolean);

fs.mkdirSync(path.join(ROOT, 'static'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'static', 'structure.json'), JSON.stringify({ source: 'sidebars.js', tree }, null, 2));

const count = (nodes) => nodes.reduce((a, n) => a + (n.type === 'doc' ? 1 : count(n.items || [])), 0);
console.log(`[structure] wrote static/structure.json — ${tree.length} top-level groups, ${count(tree)} docs, ${missing} missing`);
